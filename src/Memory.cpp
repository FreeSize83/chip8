#include "Memory.h"
#include <cstring>

Memory::Memory() {
  reset();
}

void Memory::loadFontset() {
  static const uint8_t font[80] = {0xF0, 0x90, 0x90, 0x90, 0xF0, 0x20, 0x60, 0x20, 0x20, 0x70, 0xF0, 0x10, 0xF0, 0x80,
                                   0xF0, 0xF0, 0x10, 0xF0, 0x10, 0xF0, 0x90, 0x90, 0xF0, 0x10, 0x10, 0xF0, 0x80, 0xF0,
                                   0x10, 0xF0, 0xF0, 0x80, 0xF0, 0x90, 0xF0, 0xF0, 0x10, 0x20, 0x40, 0x40, 0xF0, 0x90,
                                   0xF0, 0x90, 0xF0, 0xF0, 0x90, 0xF0, 0x10, 0xF0, 0xF0, 0x90, 0xF0, 0x90, 0x90, 0xE0,
                                   0x90, 0xE0, 0x90, 0xE0, 0xF0, 0x80, 0x80, 0x80, 0xF0, 0xE0, 0x90, 0x90, 0x90, 0xE0,
                                   0xF0, 0x80, 0xF0, 0x80, 0xF0, 0xF0, 0x80, 0xF0, 0x80, 0x80};
  std::memcpy(mem.data() + 0x50, font, 80);
}

void Memory::reset() {
  mem.fill(0);
  loadFontset();
}

uint8_t Memory::read8(uint16_t a) const {
  return a < SIZE ? mem[a] : 0;
}

void Memory::write8(uint16_t a, uint8_t v) {
  if (a < SIZE)
    mem[a] = v;
}
